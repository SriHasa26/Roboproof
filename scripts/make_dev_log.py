"""Generate docs/DEVELOPMENT_LOG.md from git itself (commits, tags, dates, hashes) and the recorded study summaries.
Nothing here is hand-written: re-run it to refresh. Dates are git's own author dates (ISO, with the committer's UTC offset) and the
run timestamps stored in each run's LABEL.json (container clock, UTC).

  python scripts/make_dev_log.py            # writes docs/DEVELOPMENT_LOG.md
"""
import json
import subprocess
import sys
from collections import OrderedDict
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.core.stats import wilson  # noqa: E402


def git(*a: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *a], capture_output=True, text=True, check=True).stdout.strip()


def jl(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def study_row(name: str, title: str) -> str:
    s = jl(ROOT / "recorded_runs" / name / "summary.json")
    a = s["aggregate"]
    vc = a["verdict_counts"]
    n = a.get("runs") or sum(vc.values())
    k = vc.get("VERIFIED", 0)
    lo, hi = wilson(k, n)
    return f"| {title} | `{s.get('pipeline_version', '?')}` | {n} | {k} | {vc.get('FAILED', 0)} | {vc.get('ERROR (no verdict)', 0)} | {k}/{n} = {100 * k / n:.0f}% [{100 * lo:.1f}%, {100 * hi:.1f}%] |"


def main() -> None:
    commits = [ln.split("\t", 3) for ln in git("log", "--reverse", "--format=%h\t%H\t%aI\t%s").splitlines()]
    tags = [ln.split("\t") for ln in git("tag", "-l", "--format=%(refname:short)\t%(creatordate:iso-strict)\t%(objectname:short)\t%(*objectname:short)").splitlines()]
    out: list[str] = []
    w = out.append
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    w("# Development log")
    w("")
    w(f"Generated by `scripts/make_dev_log.py` on {now} from this repository's git history and the recorded study summaries. Nothing here is hand-written; "
      "regenerate it to refresh. Dates are git author dates (ISO 8601 with the author's UTC offset). Commit hashes can be checked with `git show <hash>`.")
    w("")
    w(f"**{len(commits)} commits**, first {commits[0][2]} (`{commits[0][0]}`), latest {commits[-1][2]} (`{commits[-1][0]}`).")
    w("")
    w("## Freeze tags")
    w("")
    w("| Tag | Created | Commit | Meaning |")
    w("|---|---|---|---|")
    meaning = {"sim-frozen": "simulator, policy bounds and golden results fingerprinted; held-out guard in place", "pipeline-frozen": "pipeline v1 frozen (superseded)",
               "pipeline-frozen-v2": "pipeline v2 frozen: prompts, generator, evidence, analyst, fixer, selection rule, gate, thresholds, ledger, protocol"}
    for t in tags:
        name, when, obj, deref = (t + [""] * 4)[:4]
        w(f"| `{name}` | {when} | `{deref or obj}` | {meaning.get(name, '')} |")
    w("")
    w("These are lightweight tags, so the date shown is the date of the tagged commit.")
    w("")
    w("## Studies and the official batch (from the recorded summaries)")
    w("")
    w("| Study | Pipeline | Runs | VERIFIED | FAILED | No verdict | VERIFIED rate (Wilson 95%) |")
    w("|---|---|---|---|---|---|---|")
    w(study_row("reliability_001", "v1 rehearsal (rehearsal seeds)"))
    w(study_row("reliability_002", "v2 rehearsal (rehearsal seeds)"))
    off = jl(ROOT / "recorded_runs" / "official_001" / "official_summary.json")
    a = off["aggregate"]
    k, n = a["verified_rate"]["verified"], a["verified_rate"]["of_runs"]
    lo, hi = wilson(k, n)
    w(f"| v2 OFFICIAL (held-out seeds, pre-registered) | `{off['pipeline_version']}` | {n} | {k} | {a['verdict_counts'].get('FAILED', 0)} | {a['verdict_counts'].get('ERROR (no verdict)', 0)} | {k}/{n} = {100 * k / n:.0f}% [{100 * lo:.1f}%, {100 * hi:.1f}%] |")
    w("")
    w("Small samples with overlapping intervals: the three rows are reported together, not as a proven improvement.")
    w("")
    w("## Order of the pre-registered official evaluation")
    w("")
    protocol = next(c for c in commits if c[3].startswith("P4.6 3: pre-registered official protocol"))
    v2tag = (next(t for t in tags if t[0] == "pipeline-frozen-v2") + [""] * 4)[:4]
    labels = sorted((ROOT / "recorded_runs" / "official_001").glob("official_*/LABEL.json"))
    starts = [(p.parent.name, datetime.strptime(jl(p)["started"], "%Y-%m-%d %H:%M:%S").replace(tzinfo=timezone.utc)) for p in labels]
    w("| Step | When | Evidence |")
    w("|---|---|---|")
    w(f"| Protocol committed (K=5, fixed seeds, reporting and repeat rules) | {protocol[2]} | commit `{protocol[0]}` |")
    w(f"| Pipeline v2 frozen | {v2tag[1]} | tag `{v2tag[0]}` (commit `{v2tag[3] or v2tag[2]}`) |")
    for rid, t in starts:
        w(f"| {rid} started | {t:%Y-%m-%d %H:%M:%S} UTC | `LABEL.json` (container clock) |")
    first = min(t for _, t in starts)
    pdt = datetime.fromisoformat(protocol[2]).astimezone(timezone.utc)
    w("")
    w(f"The protocol commit ({pdt:%Y-%m-%d %H:%M:%S} UTC) is {(first - pdt).total_seconds() / 60:.0f} minutes before the first official run started ({first:%Y-%m-%d %H:%M:%S} UTC). "
      "`python scripts/verify_official.py` re-checks this, the seed ledger and the frozen-pipeline hash.")
    w("")
    w("## Commits by day")
    w("")
    by_day: "OrderedDict[str, list]" = OrderedDict()
    for c in commits:
        by_day.setdefault(c[2][:10], []).append(c)
    for day, cs in by_day.items():
        w(f"### {day} ({len(cs)} commits)")
        w("")
        w("| Time | Commit | Subject |")
        w("|---|---|---|")
        for h, _full, when, subj in cs:
            w(f"| {when[11:19]} | `{h}` | {subj[:170].replace('|', '/')}{'...' if len(subj) > 170 else ''} |")
        w("")
    path = ROOT / "docs" / "DEVELOPMENT_LOG.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)} ({len(commits)} commits, {len(tags)} tags)")


if __name__ == "__main__":
    main()
