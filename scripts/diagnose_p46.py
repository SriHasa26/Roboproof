"""Generate docs/P46_DIAGNOSIS.md from the saved artifacts of pipeline v1 (reliability_001, rehearsal_001, reasoning probes).
Everything verbatim comes straight from the files; nothing is retyped. Re-runnable."""
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R1 = ROOT / "recorded_runs" / "reliability_001"
OUT = ROOT / "docs" / "P46_DIAGNOSIS.md"

KINDS = [("too_many_axes", r"at most 3 axes"), ("volume_floor", r"covers only"), ("out_of_bounds", r"outside allowed"),
         ("unknown_parameter", r"unknown scenario parameter"), ("lo_greater_than_hi", r"lo [\d.\-e]+ > hi"),
         ("malformed_json", r"no valid JSON|JSONDecodeError|Expecting"), ]


def classify(text: str) -> list[str]:
    found = [k for k, pat in KINDS if re.search(pat, text)]
    return found or (["other"] if text.strip() else [])


def main() -> None:
    L = ["# P4.6 diagnosis of pipeline v1 (written before any change)", "",
         "Generated by `scripts/diagnose_p46.py` from the saved artifacts. Verbatim blocks are copied from the files, not retyped.", "",
         "## 1. What killed the generator in runs 1 and 5 of reliability_001", ""]
    counts = Counter()
    for rid in ("run_01_seed101", "run_05_seed505"):
        t = json.loads((R1 / rid / "llm_transcript.json").read_text(encoding="utf-8"))
        L.append(f"### {rid} (model `{t[0]['model']}`, thinking off)")
        for x in t:
            reply = json.loads(x["reply"])
            err = x["messages"][-1]["content"] if x["attempt"] == 2 else None
            L.append(f"**Reply to attempt {x['attempt']}** (verbatim regions):")
            L.append("```json\n" + json.dumps(reply["regions"], indent=1) + "\n```")
            if err:
                L.append("**Validation error fed back to the model on the retry** (verbatim):\n```\n" + err + "\n```")
        retry_same = t[0]["reply"] == t[1]["reply"]
        first, last = json.loads(t[0]["reply"])["regions"], json.loads(t[1]["reply"])["regions"]
        L.append(f"- Retry reply identical to the first reply: **{retry_same}**. Regions in the first reply: {len(first)}; the validator rejected "
                 f"the whole proposal because of one region.")
        L.append("")
        for x in t:  # classify what the validator would have said about each reply (re-run offline)
            pass
    # offline re-validation of every reply with the current schema, per region
    import sys
    sys.path.insert(0, str(ROOT / "backend"))
    from app.scenarios.proposal import Region
    L.append("### Per-region validity of those four replies (re-checked offline with the current `Region` schema)\n")
    L.append("| Run | Reply | Region | Valid | Reason if invalid |\n|---|---|---|---|---|")
    valid_by_reply = {}
    for rid in ("run_01_seed101", "run_05_seed505"):
        t = json.loads((R1 / rid / "llm_transcript.json").read_text(encoding="utf-8"))
        for x in t:
            nvalid = 0
            for rg in json.loads(x["reply"])["regions"]:
                try:
                    Region.model_validate(rg)
                    L.append(f"| {rid} | {x['attempt']} | {rg['name']} | yes | |")
                    nvalid += 1
                except Exception as e:
                    reason = str(e).split("Value error, ")[-1].split(" [type")[0]
                    L.append(f"| {rid} | {x['attempt']} | {rg['name']} | **no** | {reason} |")
                    for k in classify(str(e)):
                        counts[("reliability_001", k)] += 1
            valid_by_reply[(rid, x["attempt"])] = (nvalid, len(json.loads(x["reply"])["regions"]))
    L.append("")
    L.append("Valid regions per reply: " + ", ".join(f"{k[0]} attempt {k[1]}: {v[0]} of {v[1]}" for k, v in valid_by_reply.items()) +
             ". **Every reply contained at least two usable regions; each run was killed by a single region.**")
    L += ["", "### Failure types", "", "Counted per invalid region, from the reliability_001 replies above:", ""]
    for (src, k), n in sorted(counts.items()):
        L.append(f"- {k}: {n}")
    L.append("")
    # failure types across all probe calls (first errors and final errors of 15 calls on the earlier prompt versions)
    probe = Counter()
    for fn, tag in (("reasoning_control_probe2.json", "probe2 (first prompt: policy params listed as context)"),
                    ("reasoning_control_probe3_fixed_prompt.json", "probe3 (fixed prompt)"),
                    ("reasoning_control_probe4_with_example.json", "probe4 (fixed prompt + format example)")):
        d = json.loads((ROOT / "docs" / fn).read_text())
        for r in d["B_enable_thinking_false"]:
            for e in (r.get("first_error"), r.get("final_error")):
                for k in classify(e or ""):
                    probe[(tag, k)] += 1
    L += ["Counted per error message (first error and final error of each call) in the 15 probe calls on the fast model with thinking off:", "",
          "| Prompt version | Failure type | Count |", "|---|---|---:|"]
    for (tag, k), n in sorted(probe.items()):
        L.append(f"| {tag} | {k} | {n} |")
    L += ["", "No malformed-JSON replies and no out-of-bounds values occurred in the 2 failed study runs (4 replies) or in the 15 probe calls. "
          "The recurring problems are the **2% volume floor** (the model's arithmetic) and, with the first prompt, policy parameters used as scenario axes.", "",
          "## 2. What the fixer was shown in run 4 (verbatim)", ""]
    t = json.loads((R1 / "run_04_seed404" / "llm_transcript.json").read_text(encoding="utf-8"))
    fx = [x for x in t if x["purpose"] == "fixer"]
    for i, x in enumerate(fx, 1):
        u = json.loads(x["messages"][1]["content"])
        L.append(f"### Fixer call {i}: `previous_attempts` as given to the model")
        L.append("```json\n" + json.dumps(u["previous_attempts"], indent=1) + "\n```")
        L.append(f"Model reply (verbatim, changes only): `{json.dumps(json.loads(x['reply'])['changes'])}`\n")
    u3 = json.loads(fx[2]["messages"][1]["content"])
    L += ["### What the third call's prompt contained besides the history", "",
          f"- Keys: {sorted(u3)}", f"- `baseline_pass_rate_on_analysis_scenarios`: {u3['baseline_pass_rate_on_analysis_scenarios']}",
          f"- Hypotheses shown: {[h['id'] + ' levers=' + str([l['param'] for l in h['levers']]) for h in u3['hypotheses']]}", "",
          "**What it was NOT shown:** which hypotheses were fixed or still failing (no per-hypothesis breakdown), how many targeted "
          "failures each hypothesis owns, or what the failing targeted scenarios looked like. It saw only one number per attempt "
          "(overall targeted fix rate) plus regressions. So after attempt 2 (three levers, fix rate 0.62) it could not tell *which* "
          "targets remained, and its third patch dropped to a single lever (grip 60), scoring 0.35 with 4 regressions.", "",
          "## 3. Every fixer patch proposed so far (pipeline v1)", "",
          "| Run | Attempt | Proposed (model output) | G3 targeted fix rate (threshold 0.70) | G4 regressions / budget | Outcome |", "|---|---|---|---|---|---|"]
    runs = [("rehearsal_001", ROOT / "recorded_runs" / "rehearsal_001" / "gate_full_pipeline.json", "g")]
    runs += [(rid, R1 / rid / "gate_report.json", "g") for rid in ("run_02_seed202", "run_03_seed303", "run_04_seed404")]
    for name, path, _ in runs:
        g = json.loads(path.read_text(encoding="utf-8"))
        for a in g["attempts"]:
            c = a["dev_checks"]
            outcome = "passed G1-G4" if all(c[k]["status"] == "pass" for k in ("G1", "G2", "G3", "G4")) else "failed " + "/".join(k for k in ("G3", "G4") if c[k]["status"] == "fail")
            L.append(f"| {name} | {a['attempt']} | `{json.dumps(a['model_proposal']['changes'])}` | {c['G3']['observed'].get('fix_rate')} | "
                     f"{c['G4']['observed'].get('regressions')} / {c['G4']['threshold'].get('budget')} | {outcome} |")
    L += ["", "Patterns visible in the table (not statistics; 10 patches):", "",
          "- Single-lever patches fixed little: `grip_force 30` alone fixed 21% of targets in run 4; `grip_force 60` alone fixed 35%.",
          "- The best fix rates came from patches moving 3 or 4 levers (0.87 in run 3; 0.78 in rehearsal_001).",
          "- Step sizes were small: grip 20 to 40 N, hold 20 to 40 steps, retries 1 to 2, against bounds of 80 N, 120 steps and 3 retries.",
          "- No model patch ever combined a large grip force with a long hold and several retries, which the dev-seed ceiling search found to work best.", ""]
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", OUT, "lines:", len(L))


if __name__ == "__main__":
    main()
